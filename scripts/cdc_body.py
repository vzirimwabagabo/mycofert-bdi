ROMAN = {1: 'i', 2: 'ii', 3: 'iii', 4: 'iv', 5: 'v'}


class TocDocTemplate(SimpleDocTemplate):
    """TOC + numérotation conforme : préliminaires en romain, corps réinitialisé à 1."""

    def beforeDocument(self):
        # Valeur du passage précédent (stabilisée par multiBuild) pour le pied de page.
        self._prev_first_content = getattr(self, 'first_content_page', None)
        self.first_content_page = None
        self.fixed_f = int(os.environ.get('CDC_FIXED_F', '0') or 0)

    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            if self.first_content_page is None:
                self.first_content_page = self.page
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            f = self.fixed_f or self.first_content_page
            display = self.page - f + 1
            self.notify('TOCEntry', (level, text, display, key))


def on_page(canvas, doc):
    """En-tête + pied de page (i pour la table des matières, 1,2,3… pour le corps)."""
    canvas.saveState()
    # En-tête : titre courant + filet accent
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 40, 'Cahier des charges — Site web institutionnel bilingue')
    canvas.drawRightString(PAGE_W - MARGIN, PAGE_H - 40, 'MYCOFERT Burundi')
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 46, PAGE_W - MARGIN, PAGE_H - 46)
    # Pied de page : auteur à gauche, numéro à droite, filet léger
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 42, PAGE_W - MARGIN, 42)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 30, 'Document de référence — version 1.0')
    fixed_f = getattr(doc, 'fixed_f', 0)
    first_content = fixed_f or getattr(doc, '_prev_first_content', None) or 2
    if doc.page < first_content:
        num = ROMAN.get(doc.page, str(doc.page))
    else:
        num = str(doc.page - first_content + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 30, num)
    canvas.restoreState()

