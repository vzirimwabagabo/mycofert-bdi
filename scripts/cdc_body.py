def add_heading(text, style, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1(story, text):
    story.append(CondPageBreak(H1_THRESHOLD))
    story.append(Spacer(1, 10))
    head = add_heading(text, S['h1'], level=0)
    rule = HRFlowable(width='100%', thickness=1.2, color=ACCENT,
                      spaceBefore=2, spaceAfter=12)
    story.append(KeepTogether([head, rule]))


def h2(story, text):
    story.append(add_heading(text, S['h2'], level=1))


def h3(story, text):
    story.append(Paragraph('<b>%s</b>' % text, S['h3']))


def para(story, text, style='body'):
    story.append(Paragraph(text, S[style]))


def bullets(story, items):
    for it in items:
        story.append(Paragraph(it, S['bullet'], bulletText='•'))
    story.append(Spacer(1, 4))


def make_table(header, rows, ratios, caption=None, align_center_cols=()):
    """Tableau normalisé : toutes les cellules en Paragraph, largeur ≤ AVAIL_W."""
    assert abs(sum(ratios) - 1.0) < 0.001, 'ratios must sum to 1'
    col_widths = [r * AVAIL_W for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5, 'table exceeds available width'
    data = [[Paragraph('<b>%s</b>' % c, S['th_c'] if i in align_center_cols else S['th'])
             for i, c in enumerate(header)]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = S['cell_c'] if i in align_center_cols else S['cell']
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]
    for idx in range(1, len(data)):
        bg = TABLE_ROW_ODD if idx % 2 == 1 else TABLE_ROW_EVEN
        style.append(('BACKGROUND', (0, idx), (-1, idx), bg))
    t.setStyle(TableStyle(style))
    return t


def add_table(story, header, rows, ratios, caption=None, align_center_cols=()):
    story.append(Spacer(1, 10))
    t = make_table(header, rows, ratios, caption, align_center_cols)
    if len(rows) <= 12:
        block = [t]
        if caption:
            block.append(Paragraph(caption, S['caption']))
        story.append(KeepTogether(block))
    else:
        story.append(t)
        if caption:
            story.append(Paragraph(caption, S['caption']))
    story.append(Spacer(1, 10))


